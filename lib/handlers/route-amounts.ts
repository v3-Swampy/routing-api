import JSBI from 'jsbi'
import { V2PoolInRoute, V3PoolInRoute } from './schema'

type PoolInRoute = V2PoolInRoute | V3PoolInRoute
type EdgeAmountField = 'amountIn' | 'amountOut'

type Edge = {
  pool: PoolInRoute
  value: JSBI
}

export type ReconcileResult = {
  /**
   * Integer sum of the route amounts *before* reconciliation. This is exactly the
   * amount the calldata (generated inside the router before this point) spends.
   */
  total: JSBI
  /** amount - total: how much was added back (>0), 0 when already exact, <0 when routes exceed it. */
  missing: JSBI
}

/**
 * The smart order router splits the requested amount with `Fraction`, so each route
 * can carry a fractional amount (e.g. 95% of 50000000000000000010 is
 * 47500000000000000009.5). Only the integer `quotient` is ever quoted on-chain
 * (see `on-chain-quote-provider`), encoded in calldata and encoded by clients, so
 * the sum of the route amounts can be a few drip smaller than the requested amount.
 * For native input that difference is sent as `value` but never wrapped or
 * refunded, so it ends up stranded in the SwapRouter (whose `refundETH` is
 * unauthenticated).
 *
 * Reconcile the response on the integer level: add the missing amount to the
 * largest route (relative slippage impact is the smallest there), so the amounts
 * clients encode always add up to the requested input (exactIn) or output (exactOut).
 */
export function reconcileRouteAmounts(route: Array<PoolInRoute[]>, exactIn: boolean, amount: JSBI): ReconcileResult {
  const field: EdgeAmountField = exactIn ? 'amountIn' : 'amountOut'
  const zero = JSBI.BigInt(0)

  // Only the first pool of a route carries amountIn (exactIn), and only the last
  // pool carries amountOut (exactOut).
  const edges: Edge[] = []
  for (const subRoute of route) {
    const pool = exactIn ? subRoute[0] : subRoute[subRoute.length - 1]
    const raw = pool?.[field]
    if (!pool || raw === undefined) continue
    edges.push({ pool, value: JSBI.BigInt(raw) })
  }

  if (edges.length === 0) return { total: zero, missing: zero }

  let total = zero
  let largestIndex = 0
  for (let i = 0; i < edges.length; i++) {
    const value = edges[i]!.value
    total = JSBI.add(total, value)
    if (JSBI.greaterThan(value, edges[largestIndex]!.value)) largestIndex = i
  }

  const missing = JSBI.subtract(amount, total)
  if (JSBI.lessThanOrEqual(missing, zero)) return { total, missing }

  const target = edges[largestIndex]!
  const adjusted = JSBI.add(target.value, missing).toString()
  if (exactIn) {
    target.pool.amountIn = adjusted
  } else {
    // exactOut: the compensated route asks for a few drip more output than was
    // quoted, so its required input can be marginally higher. Clients absorb that
    // with an absolute slack on `amountInMaximum` (see the interface's handleSwap)
    // and, for native input, `refundETH` in the same multicall; deliberately leave
    // amountIn/quote untouched to keep Σ amountIn == quote.
    target.pool.amountOut = adjusted
  }

  return { total, missing }
}

/**
 * `methodParameters` is generated by the router *before* the JSON route is
 * reconciled, so its calldata spends `total` (the pre-reconciliation sum), while
 * `value` was built from the fractional sum, i.e. the full requested amount.
 * For native input the difference is wrapped nowhere and stays in the router.
 *
 * Rewrite `value` to match what the calldata actually spends. Nothing else is
 * touched: same calldata bytes, same multicall, same gas, and the dust never
 * leaves the user's wallet in the first place.
 */
export function withReconciledNativeValue<T extends { value: string }>(
  methodParameters: T | undefined,
  total: JSBI
): T | undefined {
  if (!methodParameters) return undefined
  const value = `0x${total.toString(16)}`
  if (methodParameters.value === value) return methodParameters
  return { ...methodParameters, value }
}
